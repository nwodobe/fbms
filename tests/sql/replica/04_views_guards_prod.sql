create or replace function public.sacherie_guard_mouvement_update()
returns trigger language plpgsql security definer set search_path to 'public'
as $fn$
declare
  v_fige text[] := array['local_id','date','type','source','destination','cluster','rt_id','rt_nom','producteur_id','producteur_nom','quantite','created_by','created_at','request_id','bag_movement_code','approved_qty','executed_qty','bag_state'];
  v_col text;
  v_old jsonb := to_jsonb(old);
  v_new jsonb := to_jsonb(new);
begin
  if new.type = 'DOTATION_RT' and old.type is distinct from 'DOTATION_RT' then
    raise exception 'Requalification en DOTATION_RT interdite : une dotation RT se cree uniquement par le workflow approuve (sacherie_executer_demande)' using errcode = '42501';
  end if;
  foreach v_col in array v_fige loop
    if v_old -> v_col is distinct from v_new -> v_col then
      raise exception 'Colonne % non modifiable sur un mouvement enregistre. Passer par un contre-mouvement (correction_of).', v_col using errcode = '42501';
    end if;
  end loop;
  return new;
end
$fn$;

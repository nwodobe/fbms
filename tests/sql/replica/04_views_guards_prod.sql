    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'UTILISABLE'::text)), (0)::bigint))::integer AS vides,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'PLEIN'::text)), (0)::bigint))::integer AS pleins,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'EN_TRANSIT'::text)), (0)::bigint))::integer AS transit,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'DECHIRE'::text)), (0)::bigint))::integer AS dechires,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'A_REPARER'::text)), (0)::bigint))::integer AS a_reparer,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'REPARE'::text)), (0)::bigint))::integer AS repares,
    (COALESCE(sum(s.qty) FILTER (WHERE (s.state = 'REFORME'::text)), (0)::bigint))::integer AS rebut,
    COALESCE(( SELECT (sum(x.qty))::integer AS sum FROM rcn_jute_loss_requests x
          WHERE ((x.ledger = 'INTERNE'::text) AND (x.statut = 'APPROUVE'::text))), 0) AS pertes_approuvees,

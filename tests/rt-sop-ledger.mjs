import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const s = require('../shared/rt-sop-ledger.js');
const validated = (montant) => ({ montant, statut_validation:'Valide', validated_by:'uh-test', validated_by_role:'Unit Head', validated_at:'2026-11-12T10:00:00Z' });
const pending = (montant) => ({ montant, statut_validation:'A valider', validated_by:null, validated_at:null });
const credit = (montant, verified = true) => ({ montant, statut:'Active', wave_transaction_ref:verified?'WAVE-TEST':null, finance_confirmed_at:verified?'2026-11-12T09:00:00Z':null,finance_confirmed_by:verified?'finance-test':null,rt_ack_at:verified?'2026-11-12T09:10:00Z':null,rt_ack_document_ref:verified?'signed-test':null });
let f = s.summarizeCash([credit(300000)], [validated(200000),pending(40000)], []);
assert.equal(f.remainingToJustify,100000);
assert.equal(f.purchasesPending,40000);
assert.equal(f.provisionalRemaining,60000);
f=s.summarizeCash([credit(300000)],[validated(200000),pending(40000)],[{montant:10000,confirmed_at:'2026-11-12',document_ref:'REF-TEST'}]);
assert.equal(f.remainingToJustify,90000);
f=s.summarizeCash([credit(300000,false)],[validated(200000)],[]);
assert.equal(f.remainingToJustify,null);
assert.equal(f.advancesUnverified,300000);
assert.equal(s.purchaseState({montant:40000,statut_validation:'A valider',validated_by:'uh-test',validated_at:null}),'PENDING');
assert.equal(s.purchaseState({montant:40000,statut_validation:'Valide',validated_by:'uh-test',validated_at:null}),'PENDING');
assert.equal(s.purchaseState({montant:10000,statut_validation:'Rejete',validated_by:'uh-test',validated_at:'2026-11-12'}),'REJECTED');
assert.deepEqual(s.rcnStock(300,200,195),{rtKg:100,inTransitKg:200,bevVsGrnKg:5});
assert.deepEqual(s.juteBalance(100,25,15),{emptyBags:75,fullAtRtBags:10,underRtResponsibilityBags:85});
assert.equal(s.summarizeCash([credit(100000)],[validated(0)],[]).remainingToJustify,100000);
console.log('RT-SOP accounting: assertions OK (pure calculations; no production write)');

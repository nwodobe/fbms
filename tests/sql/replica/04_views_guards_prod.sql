  WHERE ((COALESCE(l.scope_type, ''::text) = ANY (ARRAY['CLUSTER'::text, 'RT'::text, 'PRODUCTEUR'::text, 'HUB'::text, 'FACTORY'::text, 'TRANSIT'::text, 'REPARATION'::text, 'REBUT'::text])) OR (l.code ~~ 'AFLP-%'::text));

begin
  raise exception 'Suppression interdite : un mouvement de sacs enregistre est definitif. Passer par un contre-mouvement (correction_of).' using errcode = '42501';
end
$fn$;
CREATE OR REPLACE FUNCTION public.aflp_bag_allocation_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare v_limit integer; v_other integer;
begin
  select approved_qty into v_limit from public.aflp_bag_envelopes where id=new.envelope_id and status='GM_APPROVED' for update;
  if not found then raise exception 'Enveloppe AFLP GM approuvée requise'; end if;
  select coalesce(sum(allocated_qty),0)::integer into v_other from public.aflp_bag_cluster_allocations where envelope_id=new.envelope_id and id is distinct from new.id;
  if v_other+new.allocated_qty>v_limit then raise exception 'Allocation cluster supérieure au solde de l’enveloppe AFLP'; end if;
  return new;
end $function$
;
